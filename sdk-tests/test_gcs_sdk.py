from __future__ import annotations

import io
import base64
import hashlib
import hmac
from datetime import datetime, timedelta, timezone
from xml.etree import ElementTree

import pytest

google_auth = pytest.importorskip("google.auth.credentials")
gcs_storage = pytest.importorskip("google.cloud.storage")


class HmacSigningCredentials(google_auth.Signing):
    """The official signed-URL API's Signing interface, backed by a synthetic HMAC key.

    Python storage's V2 URL generator supports this signing interface; its V4
    generator hardcodes RSA, so this qualifies native V2 HMAC only.
    """

    def __init__(self, access_id, secret):
        self._access_id = access_id
        self._secret = base64.b64decode(secret)

    @property
    def signer_email(self):
        return self._access_id

    @property
    def signer(self):
        return self

    def sign_bytes(self, message):
        return hmac.new(self._secret, message, hashlib.sha1).digest()


def _native_request(
    client,
    resource,
    method,
    credentials,
    endpoint,
    *,
    data=None,
    headers=None,
    expiration=None,
):
    headers = {**(headers or {}), "content-length": str(len(data or b""))}
    url = resource.generate_signed_url(
        version="v2",
        method=method,
        credentials=credentials,
        api_access_endpoint=endpoint,
        expiration=expiration or datetime.now(timezone.utc) + timedelta(minutes=5),
        headers={
            name: value
            for name, value in (headers or {}).items()
            if name.startswith("x-goog-")
        },
        **(
            {"content_type": headers.get("content-type")}
            if isinstance(resource, gcs_storage.Blob)
            and headers
            and "content-type" in headers
            else {}
        ),
        **(
            {"content_md5": headers["content-md5"]}
            if isinstance(resource, gcs_storage.Blob) and "content-md5" in headers
            else {}
        ),
    )
    # The official client's HTTP transport consumes the URL generated by its public signing API.
    return client._http.request(method, url, data=data, headers=headers, timeout=10)


def test_gcs_native_hmac_signed_url_contract(sqrzl_server):
    sqrzl_server.require_provider("gcs")
    if not sqrzl_server.enforce_auth:
        pytest.skip("native HMAC requires the authenticated storage lane")
    client = gcs_storage.Client(
        project="sqrzl",
        credentials=google_auth.AnonymousCredentials(),
        client_options={"api_endpoint": sqrzl_server.api_url},
    )
    credentials = HmacSigningCredentials(
        sqrzl_server.gcs_hmac_access_id, sqrzl_server.gcs_hmac_secret
    )
    bucket = client.bucket(sqrzl_server.bucket_name("sdk-gcs-native"))
    blob = bucket.blob("folder/native.txt")
    request = lambda resource, method, **kwargs: _native_request(
        client, resource, method, credentials, sqrzl_server.api_url, **kwargs
    )
    assert request(bucket, "PUT", data=b"").status_code == 200
    headers = {"content-type": "text/plain", "x-goog-meta-owner": "native-sdk"}
    assert (
        request(blob, "PUT", data=b"native hmac payload", headers=headers).status_code
        == 200
    )
    fetched = request(blob, "GET")
    assert fetched.status_code == 200
    assert fetched.content == b"native hmac payload"
    assert fetched.headers["x-goog-meta-owner"] == "native-sdk"
    assert request(blob, "GET", headers={"range": "bytes=7-10"}).content == b"hmac"

    for bad_credentials, expiration, code in [
        (
            HmacSigningCredentials(
                sqrzl_server.gcs_hmac_access_id, base64.b64encode(b"wrong-key").decode()
            ),
            None,
            "SignatureDoesNotMatch",
        ),
        (
            HmacSigningCredentials("wrong-access", sqrzl_server.gcs_hmac_secret),
            None,
            "AccessDenied",
        ),
        (
            credentials,
            datetime.now(timezone.utc) - timedelta(minutes=1),
            "AccessDenied",
        ),
    ]:
        denied = _native_request(
            client,
            blob,
            "PUT",
            bad_credentials,
            sqrzl_server.api_url,
            data=b"replacement",
            expiration=expiration,
        )
        assert denied.status_code == 403
        assert ElementTree.fromstring(denied.content).findtext("Code") == code
        assert request(blob, "GET").content == b"native hmac payload"
    assert request(blob, "DELETE").status_code == 204
    assert request(bucket, "DELETE").status_code == 204


def _client(sqrzl_server):
    credentials = google_auth.AnonymousCredentials()
    if sqrzl_server.enforce_auth:
        google_oauth2 = pytest.importorskip("google.oauth2.credentials")
        credentials = google_oauth2.Credentials(token=sqrzl_server.gcs_hmac_secret)
    return gcs_storage.Client(
        project="sqrzl",
        credentials=credentials,
        client_options={"api_endpoint": sqrzl_server.api_url},
    )


@pytest.mark.parametrize("protocol", ["xml", "json"])
def test_gcs_isolated_resumable_checksum_contract(sqrzl_server, protocol):
    """Google resumable protocol: opaque sessions, 308 prefixes, hash receipts."""
    from urllib.parse import urlsplit, parse_qs
    import google_crc32c

    sqrzl_server.require_provider("gcs")
    client = _client(sqrzl_server)
    bucket = client.bucket(sqrzl_server.bucket_name("sdk-gcs-session"))
    bucket.create()
    payloads = [b"g" * (5 * 1024 * 1024) + b"first tail", b"h" * (5 * 1024 * 1024) + b"second tail"]
    checksum = lambda data: base64.b64encode(google_crc32c.value(data).to_bytes(4, "big")).decode()
    native_client = gcs_storage.Client(project="sqrzl", credentials=google_auth.AnonymousCredentials(),
                                       client_options={"api_endpoint": sqrzl_server.api_url})
    sessions = []
    for key, payload in zip(["first", "second"], payloads):
        crc = checksum(payload)
        blob = bucket.blob(key)
        if protocol == "json":
            response = client._http.post(
                f"{sqrzl_server.api_url}/upload/storage/v1/b/{bucket.name}/o",
                params={"uploadType": "resumable", "name": key},
                json={"crc32c": crc}, timeout=60,
            )
        else:
            response = _native_request(
                native_client, blob, "POST",
                HmacSigningCredentials(sqrzl_server.gcs_hmac_access_id, sqrzl_server.gcs_hmac_secret),
                sqrzl_server.api_url, data=b"",
                headers={"x-goog-resumable": "start", "content-type": "application/octet-stream"},
            )
        assert response.status_code == (200 if protocol == "json" else 201), response.text
        location = response.headers["location"]
        assert urlsplit(location).netloc == urlsplit(sqrzl_server.api_url).netloc
        assert len(parse_qs(urlsplit(location).query).get("upload_id", [])) == 1
        sessions.append(location)
    assert sessions[0] != sessions[1]
    identities = [parse_qs(urlsplit(location).query)["upload_id"][0] for location in sessions]
    assert identities[0] != identities[1]
    for malformed in [sessions[0].replace(identities[0], identities[1], 1), sessions[0] + f"&upload%5fid={identities[0]}"]:
        rejected = native_client._http.put(malformed, data=b"", headers={"content-range": "bytes */*"}, timeout=60)
        assert rejected.status_code == 400
    # Session URIs authorize the upload; do not reconstruct or re-sign them.
    for location, payload in zip(sessions, payloads):
        response = native_client._http.put(location, data=payload[:256 * 1024],
                                    headers={"content-range": f"bytes 0-{256 * 1024 - 1}/{len(payload)}"}, timeout=60)
        assert response.status_code == 308
        assert response.headers["range"] == f"bytes=0-{256 * 1024 - 1}"
    assert list(client.list_blobs(bucket)) == []
    # Incomplete prefixes survive a real child-process restart and remain isolated.
    if sqrzl_server.runtime is not None:
        sqrzl_server.restart(kill=True)
    for location, key, payload in zip(sessions, ["first", "second"], payloads):
        crc = checksum(payload)
        probe = native_client._http.put(location, data=b"", headers={"content-range": f"bytes */{len(payload)}"}, timeout=60)
        assert probe.status_code == 308
        assert probe.headers["range"] == f"bytes=0-{256 * 1024 - 1}"
        headers = {"content-range": f"bytes {256 * 1024}-{len(payload) - 1}/{len(payload)}", "x-goog-hash": "crc32c=AAAAAA=="}
        rejected = native_client._http.put(location, data=payload[256 * 1024:], headers=headers, timeout=60)
        assert rejected.status_code == 400
        if protocol == "xml":
            assert ElementTree.fromstring(rejected.content).findtext("Code") == "BadDigest"
        assert not bucket.blob(key).exists()
        headers["x-goog-hash"] = f"crc32c={crc}"
        completed = native_client._http.put(location, data=payload[256 * 1024:], headers=headers, timeout=60)
        assert completed.status_code in (200, 201), completed.text
        if protocol == "json":
            assert completed.json()["crc32c"] == crc
        else:
            assert f"crc32c={crc}" in completed.headers["x-goog-hash"]
        blob = bucket.blob(key)
        assert blob.download_as_bytes() == payload
        blob.reload()
        assert blob.crc32c == crc
        blob.delete()
    bucket.delete()


@pytest.mark.parametrize("protocol", ["xml", "json"])
@pytest.mark.parametrize("mode", ["missing", "corrupt"])
def test_gcs_resumable_checksum_receipt_faults(sqrzl_server, protocol, mode):
    import google_crc32c

    sqrzl_server.require_provider("gcs")
    client = _client(sqrzl_server)
    bucket = client.bucket(sqrzl_server.bucket_name("sdk-gcs-receipt-fault"))
    bucket.create()
    payload = b"receipt proof must describe stored bytes"
    crc = base64.b64encode(google_crc32c.value(payload).to_bytes(4, "big")).decode()
    blob = bucket.blob("key")
    if protocol == "json":
        initiated = client._http.post(f"{sqrzl_server.api_url}/upload/storage/v1/b/{bucket.name}/o", params={"uploadType": "resumable", "name": "key"}, json={"crc32c": crc}, timeout=60)
    else:
        native = gcs_storage.Client(project="sqrzl", credentials=google_auth.AnonymousCredentials(), client_options={"api_endpoint": sqrzl_server.api_url})
        initiated = _native_request(native, blob, "POST", HmacSigningCredentials(sqrzl_server.gcs_hmac_access_id, sqrzl_server.gcs_hmac_secret), sqrzl_server.api_url, data=b"", headers={"x-goog-resumable": "start"})
    assert initiated.status_code in (200, 201), initiated.text
    completed = client._http.put(initiated.headers["location"], data=payload, headers={"x-goog-hash": f"crc32c={crc}", "x-sqrzl-failpoint": f"checksum-receipt-{mode}"}, timeout=60)
    assert completed.status_code in (200, 201), completed.text
    assert completed.headers["x-sqrzl-failpoint-applied"] == f"checksum-receipt-{mode}"
    receipt = completed.json().get("crc32c") if protocol == "json" else completed.headers.get("x-goog-hash")
    assert receipt is None if mode == "missing" else crc not in receipt
    blob.reload()
    assert blob.crc32c == crc
    assert blob.download_as_bytes(if_generation_match=blob.generation) == payload
    blob.delete()
    bucket.delete()


def test_gcs_core_json_workflows(sqrzl_server):
    sqrzl_server.require_provider("gcs")
    client = _client(sqrzl_server)
    bucket_name = sqrzl_server.bucket_name("sdk-gcs-core")
    blob_name = "folder/hello.txt"

    bucket = client.bucket(bucket_name)
    bucket.create()
    blob = bucket.blob(blob_name)
    blob.metadata = {"owner": "support"}
    blob.upload_from_string("hello gcs sdk", content_type="text/plain")

    blob.reload()
    assert blob.metadata["owner"] == "support"
    assert blob.size == len(b"hello gcs sdk")

    assert blob.download_as_bytes(start=6, end=8) == b"gcs"
    assert [item.name for item in client.list_blobs(bucket, prefix="folder/")] == [
        blob_name
    ]

    blob.delete()
    bucket.delete()


def test_gcs_resumable_upload_workflow(sqrzl_server):
    sqrzl_server.require_provider("gcs")
    client = _client(sqrzl_server)
    bucket_name = sqrzl_server.bucket_name("sdk-gcs-resumable")
    blob_name = "large/resumable.txt"

    bucket = client.bucket(bucket_name)
    bucket.create()
    blob = bucket.blob(blob_name)
    payload = b"g" * (9 * 1024 * 1024 + 17)
    blob.chunk_size = 256 * 1024
    blob.upload_from_file(
        io.BytesIO(payload),
        rewind=True,
        size=len(payload),
        content_type="text/plain",
    )

    assert blob.download_as_bytes() == payload
    blob.delete()
    bucket.delete()


def test_gcs_xml_upload_integrity_headers(sqrzl_server):
    sqrzl_server.require_provider("gcs")
    client = _client(sqrzl_server)
    bucket = client.bucket(sqrzl_server.bucket_name("sdk-gcs-xml-integrity"))
    bucket.create()
    native_client = gcs_storage.Client(
        project="sqrzl",
        credentials=google_auth.AnonymousCredentials(),
        client_options={"api_endpoint": sqrzl_server.api_url},
    )
    blob = bucket.blob("checksummed")
    credentials = HmacSigningCredentials(
        sqrzl_server.gcs_hmac_access_id, sqrzl_server.gcs_hmac_secret
    )
    payload = b"streamed integrity payload"
    digest = base64.b64encode(hashlib.md5(payload).digest()).decode("ascii")
    import google_crc32c

    crc = base64.b64encode(google_crc32c.value(payload).to_bytes(4, "big")).decode("ascii")
    response = _native_request(
        native_client, blob, "PUT", credentials, sqrzl_server.api_url,
        data=payload, headers={"content-md5": digest, "x-goog-hash": f"md5={digest},crc32c={crc}"},
    )
    assert response.status_code == 200
    original_etag = response.headers["etag"]
    for headers, code in (
        ({"content-md5": "not-base64"}, "InvalidDigest"),
        ({"content-md5": "AAAAAAAAAAAAAAAAAAAAAA=="}, "BadDigest"),
        ({"x-goog-hash": "crc32c=AAAAAA=="}, "BadDigest"),
        ({"x-goog-hash": "md5=AAAAAAAAAAAAAAAAAAAAAA=="}, "BadDigest"),
        ({"x-goog-hash": "crc32c=bad"}, "InvalidHash"),
    ):
        rejected = _native_request(
            native_client, blob, "PUT", credentials, sqrzl_server.api_url,
            data=b"rejected replacement", headers=headers,
        )
        assert rejected.status_code == 400
        assert ElementTree.fromstring(rejected.content).findtext("Code") == code
        fetched = _native_request(native_client, blob, "GET", credentials, sqrzl_server.api_url)
        assert fetched.status_code == 200
        assert fetched.content == payload
        assert fetched.headers["etag"] == original_etag
    blob.delete()
    bucket.delete()
